import { readFile } from 'node:fs/promises'

/** Reuse the packaged-app CDP connection and its isolated synthetic project. */
export async function checkEditorWorkflow(cdp, projectPath, screenshotPath) {
  const focusTimeline = () => cdp.evaluate(`document.querySelector('[aria-label="时间线编辑区"], [aria-label="Timeline editor"]')?.focus()`)
  const key = async (code, keyValue, virtualKey, modifiers = 0) => {
    const event = { code, key: keyValue, windowsVirtualKeyCode: virtualKey, modifiers }
    await cdp.send('Input.dispatchKeyEvent', { ...event, type: 'rawKeyDown' })
    await cdp.send('Input.dispatchKeyEvent', { ...event, type: 'keyUp' })
  }
  const clickLabel = async (label) => {
    const clicked = await cdp.evaluate(`(() => {
      const element = [...document.querySelectorAll('button')].find((item) => item.getAttribute('aria-label') === ${JSON.stringify(label)})
      if (!element) return false
      element.click()
      return true
    })()`)
    if (!clicked) throw new Error(`Missing button: ${label}`)
  }
  const time = `Number(document.querySelector('[data-preview-timeline-time]')?.dataset.previewTimelineTime || 0)`
  await cdp.evaluate(`document.querySelector('button[aria-label="暂停"], button[aria-label="Pause"]')?.click()`)
  await cdp.evaluate(`[...document.querySelectorAll('button')].find((item) => ['适配', 'Fit'].includes(item.textContent.trim()))?.click()`)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 2`)
  await focusTimeline()
  await key('F1', 'F1', 112)
  await cdp.waitFor(`document.querySelector('[role="dialog"]')?.textContent.includes('删除并关闭空隙')`)
  await new Promise((resolve) => setTimeout(resolve, 500))
  await cdp.capture(screenshotPath.replace(/\.png$/i, '-shortcuts-dark.png'))
  await key('Escape', 'Escape', 27)
  await cdp.waitFor(`!document.querySelector('[role="dialog"]')`)
  await clickLabel('Switch to English')
  await clickLabel('Switch to light mode')
  await focusTimeline()
  await key('F1', 'F1', 112)
  await cdp.waitFor(`document.querySelector('[role="dialog"]')?.textContent.includes('Delete and close gaps')`)
  await new Promise((resolve) => setTimeout(resolve, 500))
  await cdp.capture(screenshotPath.replace(/\.png$/i, '-shortcuts-light.png'))
  await key('Escape', 'Escape', 27)
  await cdp.waitFor(`!document.querySelector('[role="dialog"]')`)
  await clickLabel('Switch to dark mode')
  await clickLabel('切换为中文')
  await focusTimeline()
  await key('KeyA', 'a', 65, 2)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip][data-selected="true"]').length === 2`)
  await key('Escape', 'Escape', 27)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip][data-selected="true"]').length === 0`)
  await key('Home', 'Home', 36)
  await cdp.waitFor(`${time} < 0.01`)
  await key('ArrowDown', 'ArrowDown', 40)
  await cdp.waitFor(`Math.abs(${time} - 4) < 0.01`)
  await key('ArrowUp', 'ArrowUp', 38)
  await cdp.waitFor(`${time} < 0.01`)
  await key('KeyA', 'a', 65, 2)
  await key('KeyC', 'c', 67, 2)
  await key('End', 'End', 35)
  await key('KeyV', 'v', 86, 2)
  // Fit reveals all clips, including pasted ones beyond the previous viewport.
  await cdp.evaluate(`[...document.querySelectorAll('button')].find((item) => item.textContent.trim() === '适配')?.click()`)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 4`)
  await focusTimeline()
  await key('KeyZ', 'z', 90, 2)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 2`)
  await key('KeyZ', 'Z', 90, 10)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 4`)
  await key('KeyZ', 'z', 90, 2)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 2`)
  await cdp.evaluate(`document.querySelector('[data-timeline-clip]')?.click()`)
  await focusTimeline()
  await key('Delete', 'Delete', 46, 8)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 1 && ${time} <= 4`)
  await key('KeyZ', 'z', 90, 2)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 2`)
  await key('KeyA', 'a', 65, 2)
  await key('Delete', 'Delete', 46)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 0`)
  await key('KeyS', 's', 83, 2)
  await cdp.waitFor(`document.body.innerText.includes('项目已保存')`)
  const saved = JSON.parse(await readFile(projectPath, 'utf8'))
  if (saved.clips.length !== 0 || saved.currentTime !== 0) throw new Error('Empty timeline did not persist correctly')
  await key('KeyZ', 'z', 90, 2)
  await cdp.waitFor(`document.querySelectorAll('[data-timeline-clip]').length === 2`)
  const errors = cdp.events.filter((event) => event.method === 'Runtime.exceptionThrown')
  if (errors.length) throw new Error(`Renderer exceptions: ${JSON.stringify(errors)}`)
  console.log('Editor workflow UI QA: help in both themes/languages, navigation, selection, clipboard, history, ripple delete and empty save passed')
}
